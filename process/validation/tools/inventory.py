"""Enumerate the frozen source contracts, retaining signatures/default expressions."""
import argparse
import ast
from common import ROOT, COMMIT, read_json, write_json


def families(path):
    stem = path.stem
    if 'server' in path.parts or 'handlers' in path.parts:
        return {'keys':'C01','datasets':'C02','metadata':'C03','colormap':'C04','singleband':'C05','rgb':'C06','compute':'C07','fields':'C08','flask_api':'C11','spec':'C11','app':'C28'}.get(stem,'C11')
    if 'scripts' in path.parts:
        return {'serve':'C21','ingest':'C22','optimize_rasters':'C23','connect':'C24','migrate':'C25'}.get(stem,'C26')
    if 'drivers' in path.parts:
        return {'sqlite_meta_store':'C15','sqlite_remote_meta_store':'C16','mysql_meta_store':'C17','postgresql_meta_store':'C18','paths':'C19','geotiff_raster_store':'C12','terracotta_driver':'C27','base_classes':'C27','relational_meta_store':'C15'}.get(stem,'C19')
    return {'config':'C26','expressions':'C07','image':'C08','raster':'C13','xyz':'C10','cache':'C29','logs':'C30','profile':'C30'}.get(stem, 'C09' if 'cmaps' in path.parts else 'C27')


def generate(source, output):
    records=[]
    for path in sorted((source/'terracotta').rglob('*.py')):
        if path.name == '_version.py': continue
        text=path.read_text(); tree=ast.parse(text)
        rel=path.relative_to(source).as_posix(); family=families(path)
        tests=[p.relative_to(source).as_posix() for p in (source/'tests').rglob(f'test_{path.stem}.py')]
        if not tests:
            tests = ['tests/drivers/test_drivers.py'] if 'drivers' in path.parts else ['tests/server/test_flask_api.py'] if 'server' in path.parts else []
        def record(node,name,kind,contract):
            records.append(dict(family=family,name=name,kind=kind,source=f'{rel}:{node.lineno}',contract=contract,tests=tests,implementation='not-started',verification='not-run'))
        def visit(nodes, prefix=''):
            for n in nodes:
                if isinstance(n,ast.ClassDef):
                    visit(n.body, prefix+n.name+'.')
                elif isinstance(n,(ast.FunctionDef,ast.AsyncFunctionDef)):
                    if not n.name.startswith('_') or n.name in ('__init__','__enter__','__exit__'):
                        record(n,prefix+n.name,'call',f'({ast.unparse(n.args)}) -> {ast.unparse(n.returns) if n.returns else "unspecified"}')
                    for d in n.decorator_list:
                        if isinstance(d,ast.Call) and isinstance(d.func,ast.Attribute) and d.func.attr in ('route','option','argument','command','group'):
                            record(d,prefix+n.name, d.func.attr,ast.unparse(d))
                elif isinstance(n,(ast.Assign,ast.AnnAssign)):
                    names=[ast.unparse(t) for t in n.targets] if isinstance(n,ast.Assign) else [ast.unparse(n.target)]
                    for name in names:
                        if n.value and (name.isupper() or (prefix.endswith('Schema.') and not name.startswith('_'))):
                            record(n,prefix+name,'setting/field/constant',ast.unparse(n.value))
        visit(tree.body)
    write_json(output,dict(reference_commit=COMMIT,records=records))
    lines=['# Frozen reference contract inventory','','Generated by `process/validation/tools/inventory.py`; each row is unimplemented in Rust.',
           'Source links refer to the exact baseline commit. Test pointers identify related tests,',
           'not proof that the test covers every option. Capture coverage is listed separately.',
           '', '| Family | Contract | Source | Related tests |','| --- | --- | --- | --- |']
    for r in records:
        p,line=r['source'].rsplit(':',1)
        url=f'https://github.com/DHI/terracotta/blob/{COMMIT}/{p}#L{line}'
        desc=(r['name']+': '+r['contract']).replace('|','&#124;').replace('\n',' ')
        lines.append(f'| {r["family"]} | `{desc}` | [{r["source"]}]({url}) | '+', '.join('`'+t+'`' for t in r['tests'])+' |')
    output.with_suffix('.md').write_text('\n'.join(lines)+'\n')
    print(f'{len(records)} contracts')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=__import__('pathlib').Path,default=ROOT/'.cache/reference')
    p.add_argument('--output',type=__import__('pathlib').Path,default=ROOT/'process/validation/reference/contracts.json')
    a=p.parse_args(); generate(a.source,a.output)
